"""Night 6: tonight's concept questions (table design: data types, DECIMAL vs FLOAT for money, VARCHAR vs CHAR, VARCHAR vs TEXT,
utf8 vs utf8mb4, collation, AUTO_INCREMENT / SERIAL / IDENTITY, NOT NULL and DEFAULT, CHECK, composite keys, surrogate vs natural
keys, ON DELETE CASCADE, one-to-many and many-to-many, DATETIME vs TIMESTAMP, dates kept as text, ENUM vs a lookup table, ALTER
TABLE, BOOLEAN, UUID vs auto-increment, indexes on foreign keys, CREATE TABLE, phone number types) through the real chat endpoint,
in English, Hinglish and Hindi. Each phrasing gets its concept, never the query checker, the error diagnoser, the connect step or
'no specific answer'; and real work (a pasted CREATE TABLE, a pasted error) still goes where it should."""

import json
import re

import pytest

from app.dbknow import concepts as K
from tests.test_ml import say

WRONG_PLACES = re.compile(r"I don't have a specific answer|paste (the|your|a) (sql )?query|query paste karo|Just tell me where your database is|"
                          r"connect your database|This usually comes from one of these|Bas batao database kahan hai", re.I)

NIGHT6 = ["data_types", "decimal_vs_float", "varchar_vs_char", "varchar_vs_text", "utf8mb4", "collation", "auto_increment",
          "not_null_default", "check_constraint", "composite_key", "surrogate_natural_key", "on_delete_cascade", "relationships",
          "datetime_vs_timestamp", "dates_as_text", "enum_vs_lookup", "alter_table", "boolean_type", "uuid_vs_auto_increment", "fk_index",
          "create_table", "phone_number_type"]


def fresh(client):
    client.post("/api/new-chat")
    client.cookies.clear()


def test_tonights_concepts_are_complete():
    ids = {c["id"] for c in K.concepts()}
    funds = json.load(open("app/dbknow/core/query_fundamentals.json"))["fundamentals"]
    assert set(NIGHT6) <= ids and len(NIGHT6) >= 15
    for cid in NIGHT6:
        c = K.by_id(cid)
        assert all(len(c["phrasings"][k]) >= 1 for k in ("en", "hinglish", "hindi")) and sum(len(v) for v in c["phrasings"].values()) >= 3
        assert all(c["answer"][k] and c["mistake"][k] for k in ("en", "hinglish", "hindi")), cid
        assert set(c["proven"]) >= {"mariadb", "postgresql"}, cid
        assert c["examples"] and all(e.get("result") is not None or isinstance(e.get("changed"), int) for e in c["examples"]), cid
        assert c["source"].startswith(("https://dev.mysql.com/", "https://www.postgresql.org/docs/", "https://mariadb.com/kb/")), cid
        assert set(c["engines"]) >= {"mysql", "mariadb", "postgresql"} and set(c["fundamentals"]) <= set(funds), cid
        assert all(K.by_id(r) for r in c["related"]), cid


@pytest.mark.parametrize("cid", NIGHT6)
def test_every_phrasing_of_tonights_concepts(client, ml_mode, cid):
    c = K.by_id(cid)
    titles = set(c["title"].values())
    for lang, phr in c["phrasings"].items():
        for text in phr:
            fresh(client)
            r = say(client, text)
            assert r["relation"] == "concept" and r["reply"].split("\n", 1)[0] in titles and not WRONG_PLACES.search(r["reply"]), \
                (lang, text, r["relation"], r["reply"][:200])


