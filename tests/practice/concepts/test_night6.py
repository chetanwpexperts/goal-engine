def test_a_named_database_gets_its_own_syntax():
    ex = lambda text: text.split("Example", 1)[1].split("Common mistake")[0]   # noqa: E731 - the example shown
    pg, _ = K.answer(K.match("how to make an auto increment id in postgresql"), "how to make an auto increment id in postgresql")
    assert "GENERATED BY DEFAULT AS IDENTITY" in ex(pg) and "AUTO_INCREMENT" not in ex(pg)
    my, _ = K.answer(K.match("what is auto increment in mysql"), "what is auto increment in mysql")
    assert "AUTO_INCREMENT" in ex(my) and "IDENTITY" not in ex(my)


