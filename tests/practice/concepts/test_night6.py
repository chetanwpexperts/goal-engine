    "CREATE TABLE customers (\n  id INT AUTO_INCREMENT PRIMARY KEY,\n  name VARCHAR(100)\n) ENGINE=InnoDB DEFAULT CHARSET=utf8;",
    "ERROR 1005 (HY000): Can't create table `shop`.`orders` (errno: 150 \"Foreign key constraint is incorrectly formed\")",
